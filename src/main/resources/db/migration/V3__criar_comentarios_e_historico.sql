CREATE TABLE comentarios (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id BIGINT        NOT NULL REFERENCES chamados (id),
    autor_id   BIGINT        NOT NULL REFERENCES usuarios (id),
    texto      VARCHAR(2000) NOT NULL,
    criado_em  TIMESTAMPTZ   NOT NULL
);

CREATE INDEX idx_comentarios_chamado_id ON comentarios (chamado_id);

CREATE TABLE historico_status (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chamado_id      BIGINT      NOT NULL REFERENCES chamados (id),
    status_anterior VARCHAR(30),
    status_novo     VARCHAR(30) NOT NULL,
    alterado_por_id BIGINT      NOT NULL REFERENCES usuarios (id),
    alterado_em     TIMESTAMPTZ NOT NULL
);

CREATE INDEX idx_historico_status_chamado_id ON historico_status (chamado_id);